// build.js — combines split projects into one Tampermonkey file.
//
// Usage (run from the neopets-scripts folder):
//   node build.js                 build every split project
//   node build.js <project-name>  build one project
//
// A split project has projects/<name>/src/ with numbered .js files.
// src/00-header.js must hold ONLY the // ==UserScript== header.
// The other files are joined in name order and wrapped in one function.
// Output: projects/<name>/dist/<name>.user.js

const fs = require('fs');
const path = require('path');
const { spawnSync } = require('child_process');

const root = path.join(__dirname, 'projects');
const wanted = process.argv[2];

function fail(msg) {
  console.error('FAILED: ' + msg);
  process.exitCode = 1;
}

function build(name) {
  const projectDir = path.join(root, name);
  const srcDir = path.join(projectDir, 'src');
  if (!fs.existsSync(srcDir)) {
    if (wanted) fail(`${name} has no src folder. It is a single-file project; nothing to build. Check it with: node --check <file>`);
    return;
  }

  const files = fs.readdirSync(srcDir).filter(f => f.endsWith('.js')).sort();
  if (files[0] !== '00-header.js') {
    return fail(`${name}: src/00-header.js is missing. It must hold the // ==UserScript== header.`);
  }

  const header = fs.readFileSync(path.join(srcDir, files[0]), 'utf8').trim();
  if (!header.includes('// ==UserScript==') || !header.includes('// ==/UserScript==')) {
    return fail(`${name}: src/00-header.js must contain both // ==UserScript== and // ==/UserScript==`);
  }

  const parts = files.slice(1).map(f => {
    const code = fs.readFileSync(path.join(srcDir, f), 'utf8').replace(/\s+$/, '');
    return `// ---------- src/${f} ----------\n${code}\n`;
  });

  const output =
    header + '\n\n' +
    '// Built by build.js from src/. Do not edit this file; edit src/ and rebuild.\n' +
    '(function () {\n' +
    parts.join('\n') +
    '})();\n';

  const distDir = path.join(projectDir, 'dist');
  fs.mkdirSync(distDir, { recursive: true });
  const outFile = path.join(distDir, `${name}.user.js`);
  fs.writeFileSync(outFile, output);

  const check = spawnSync(process.execPath, ['--check', outFile], { encoding: 'utf8' });
  if (check.status !== 0) {
    return fail(`${name}: syntax error in the built file.\n${check.stderr}\nFix the src file named in the "---------- src/..." comment above the error line.`);
  }

  const kb = (Buffer.byteLength(output) / 1024).toFixed(1);
  console.log(`OK  ${name}: ${files.length} files -> projects/${name}/dist/${name}.user.js (${kb} KB)`);
}

if (!fs.existsSync(root)) {
  fail('No projects folder found. Run this from the neopets-scripts folder.');
} else if (wanted) {
  if (!fs.existsSync(path.join(root, wanted))) fail(`No project called "${wanted}" in projects/.`);
  else build(wanted);
} else {
  const names = fs.readdirSync(root).filter(n => !n.startsWith('_') && fs.statSync(path.join(root, n)).isDirectory());
  names.forEach(build);
}
